"""Write assets/data.js for the project page from the analysis outputs.

    python -m cv.site_data --analysis results_cv --out assets/data.js

Accuracies are pooled over all 24 actors and averaged over each system's seeds
(as in RESULTS_CV.md); confusion matrices are the pooled matrices averaged over
seeds, i.e. expected counts for one pass over the 1440 clips.
"""
import argparse
import json
import os

import numpy as np
import pandas as pd

SPEECH = [  # (system id, page id, display name, detail)
    ("w2v_frozen_matched", "w2v_m", "wav2vec 2.0, matched probe",
     "Frozen wav2vec2-base with the shared 13-layer probe of the matched protocol"),
    ("e2v_frozen_matched", "e2v_m", "emotion2vec, matched probe",
     "Frozen emotion2vec_base with the same shared 13-layer probe and recipe"),
    ("w2v_wlp", "w2v_wlp", "wav2vec 2.0, weighted-layer probe",
     "Frozen wav2vec2-base with a weighted-layer probe (W2V2-WLP) and its own recipe"),
    ("w2v_lora", "lora", "wav2vec 2.0, LoRA",
     "LoRA (r = 4 on the query and value projections) on wav2vec2-base (W2V2-LoRA)"),
    ("e2v_lp", "e2v_lp", "emotion2vec, final-layer probe",
     "Frozen emotion2vec_base with a probe on its final layer (E2V-LP)"),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--analysis", default="results_cv")
    ap.add_argument("--out", default="assets/data.js")
    a = ap.parse_args()

    summ = pd.read_csv(os.path.join(a.analysis, "summary.csv")).set_index("system")
    inten = pd.read_csv(os.path.join(a.analysis, "intensity_accuracy.csv")).set_index("system")
    with open(os.path.join(a.analysis, "confusion_matrices.json")) as fh:
        cmj = json.load(fh)

    def block(system):
        r = summ.loc[system]
        cm = np.asarray(cmj["matrices"][system], dtype=float) / int(r["n_seeds"])
        return {"acc": round(float(r["pooled_acc"]), 4), "lo": round(float(r["pooled_acc_lo"]), 4),
                "hi": round(float(r["pooled_acc_hi"]), 4), "f1": round(float(r["pooled_f1"]), 4),
                "seeds": int(r["n_seeds"]), "cm": np.round(cm, 2).tolist(),
                "normal": round(float(inten.loc[system, "normal_acc"]), 4),
                "strong": round(float(inten.loc[system, "strong_acc"]), 4)}

    speech = [{"id": pid, "name": name, "detail": detail, "alone": block(s), "fused": block(f"{s}+fer")}
              for s, pid, name, detail in SPEECH if s in summ.index and f"{s}+fer" in summ.index]
    face = block("fer")
    cm = np.asarray(face["cm"])
    tp, sup, pred = np.diag(cm), cm.sum(1), cm.sum(0)
    p, rc = tp / np.maximum(pred, 1e-9), tp / np.maximum(sup, 1e-9)
    f1 = np.where(p + rc > 0, 2 * p * rc / np.maximum(p + rc, 1e-9), 0)
    face.update(name="Face (blendshapes + XGBoost)", prf=np.round(np.stack([p, rc, f1], 1), 3).tolist())
    data = {"labels": cmj["classes"], "speech": speech, "face": face}
    with open(a.out, "w") as fh:
        fh.write("// Generated by `python -m cv.site_data` from results_cv/ (6-fold actor-wise CV, all 24 actors).\n"
                 "// Accuracies: pooled over the 1440 clips, mean over each system's seeds, with 95% actor-bootstrap CI.\n"
                 "// Confusion matrices: pooled over folds, averaged over seeds (expected counts per pass).\n")
        fh.write("window.SER = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(f"wrote {a.out}: {len(speech)} speech systems")


if __name__ == "__main__":
    main()
